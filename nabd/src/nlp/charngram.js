// ─────────────────────────────────────────────────────────────
// فهم الكلمات الجديدة بدون قاموس: تمثيل الكلمة بـ n-gram حروف (3 حروف).
// الكلمة «بتتقيّا» و«اتقيأ» و«تقيّا» بيشتركوا في أجزاء («تقي»، «قيا»)، فيتقارب تمثيلهم حتى لو الكلمة
// نفسها لم تُكتب في أي قاموس. نفس فكرة fastText، لكن بمتجهات TF-IDF بسيطة (مادة المحاضرات) وبدون تدريب ثقيل.
// ─────────────────────────────────────────────────────────────
import { norm } from './preprocess.js'

/** n-grams لكلمة واحدة مع علامتي بداية/نهاية: «نزف» → #نز نزف زف# */
export function wordGrams(w, n = 3) {
  const s = `#${w}#`, out = []
  for (let i = 0; i + n <= s.length; i++) out.push(s.slice(i, i + n))
  return out
}
/** n-grams لنص كامل (الكلمات القصيرة جداً تُهمل لأنها ضوضاء). */
export function textGrams(text) {
  return norm(text).split(' ').filter(w => w.length > 2).flatMap(w => wordGrams(w))
}
